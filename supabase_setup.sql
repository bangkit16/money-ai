-- ==========================================================
-- TRIGGER OTOMATIS PROFIL SAAT SIGNUP
-- ==========================================================
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, is_pro, ai_daily_usage, last_ai_usage_date)
  values (new.id, false, 0, current_date)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ==========================================================
-- RPC: CEK & INCREMENT KUOTA AI
-- ==========================================================
drop function if exists public.check_and_increment_ai_usage(uuid);
create or replace function public.check_and_increment_ai_usage(p_user_id uuid)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_is_pro boolean := false;
  v_usage int := 0;
  v_last_date date;
  v_max int := 5;
begin
  if auth.uid() <> p_user_id then
    raise exception 'Unauthorized';
  end if;

  select is_pro, ai_daily_usage, last_ai_usage_date
  into v_is_pro, v_usage, v_last_date
  from public.profiles
  where id = p_user_id
  for update;

  if not found then
    insert into public.profiles (id, is_pro, ai_daily_usage, last_ai_usage_date)
    values (p_user_id, false, 0, current_date)
    returning is_pro, ai_daily_usage, last_ai_usage_date
    into v_is_pro, v_usage, v_last_date;
  end if;

  if v_last_date < current_date then
    v_usage := 0;
    v_last_date := current_date;
  end if;

  v_max := case when v_is_pro then 60 else 5 end;

  if v_usage >= v_max then
    return json_build_object(
      'allowed', false,
      'is_pro', v_is_pro,
      'current_usage', v_usage,
      'max_quota', v_max
    );
  end if;

  v_usage := v_usage + 1;

  update public.profiles
  set ai_daily_usage = v_usage,
      last_ai_usage_date = v_last_date,
      updated_at = now()
  where id = p_user_id;

  return json_build_object(
    'allowed', true,
    'is_pro', v_is_pro,
    'current_usage', v_usage,
    'max_quota', v_max
  );
end;
$$;

-- ==========================================================
-- RPC: KLAIM REWARD IKLAN AI
-- ==========================================================
drop function if exists public.add_rewarded_ai_usage();
create or replace function public.add_rewarded_ai_usage()
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_usage int;
begin
  if v_user_id is null then
    raise exception 'User not authenticated';
  end if;

  update public.profiles
  set ai_daily_usage = greatest(0, ai_daily_usage - 1),
      updated_at = now()
  where id = v_user_id
  returning ai_daily_usage into v_usage;

  return json_build_object(
    'success', true,
    'current_usage', coalesce(v_usage, 0)
  );
end;
$$;

