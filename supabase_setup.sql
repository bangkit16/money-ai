drop function if exists public.get_top_category(uuid, text, date, date);
create or replace function public.get_top_category(
  p_user_id uuid,
  p_type text,
  p_start_date date,
  p_end_date date
)
returns table (
  category text,
  total numeric
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() <> p_user_id then
    raise exception 'Unauthorized';
  end if;

  return query
  select
    coalesce(c.category, 'Lainnya') as category,
    sum(t.amount) as total
  from public.transaction t
  left join public.category_transaction c on c.id = t.category_id
  where t.user_id = p_user_id
    and t.transaction_type = p_type
    and t.transaction_date::date between p_start_date and p_end_date
  group by c.category
  order by total desc
  limit 1;
end;
$$;

drop function if exists public.get_total_transaction(uuid, text, date, date);
create or replace function public.get_total_transaction(
  p_user_id uuid,
  p_type text,
  p_start_date date,
  p_end_date date
)
returns numeric
language plpgsql
security definer
set search_path = public
as $$
declare
  v_total numeric := 0;
begin
  if auth.uid() <> p_user_id then
    raise exception 'Unauthorized';
  end if;

  select coalesce(sum(amount), 0)
  into v_total
  from public.transaction
  where user_id = p_user_id
    and transaction_type = p_type
    and transaction_date::date between p_start_date and p_end_date;

  return v_total;
end;
$$;

drop function if exists public.get_top_transaction(uuid, text, date, date, int);
create or replace function public.get_top_transaction(
  p_user_id uuid,
  p_type text,
  p_start_date date,
  p_end_date date,
  p_limit int
)
returns table (
  description text,
  amount numeric,
  category text
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() <> p_user_id then
    raise exception 'Unauthorized';
  end if;

  return query
  select
    coalesce(t.transaction, 'Tanpa keterangan') as description,
    t.amount,
    coalesce(c.category, 'Tanpa kategori') as category
  from public.transaction t
  left join public.category_transaction c on c.id = t.category_id
  where t.user_id = p_user_id
    and t.transaction_type = p_type
    and t.transaction_date::date between p_start_date and p_end_date
  order by t.amount desc
  limit greatest(1, coalesce(p_limit, 1));
end;
$$;

drop function if exists public.get_account_balances(uuid, text);
create or replace function public.get_account_balances(
  p_user_id uuid,
  p_account_name text default null
)
returns table (
  account_name text,
  balance numeric
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() <> p_user_id then
    raise exception 'Unauthorized';
  end if;

  return query
  select
    a.account_name,
    coalesce(
      (
        select coalesce(sum(t.amount), 0)
        from public.transaction t
        where t.user_id = p_user_id
          and t.account_id = a.id
          and t.transaction_type = 'INCOME'
      )
      +
      (
        select coalesce(sum(t.amount), 0)
        from public.transaction t
        where t.user_id = p_user_id
          and t.to_account_id = a.id
          and t.transaction_type = 'TRANSFER'
      )
      -
      (
        select coalesce(sum(t.amount), 0)
        from public.transaction t
        where t.user_id = p_user_id
          and t.account_id = a.id
          and t.transaction_type in ('EXPENSE', 'TRANSFER')
      ),
      0
    ) as balance
  from public.account a
  where a.user_id = p_user_id
    and (p_account_name is null or a.account_name ilike '%' || p_account_name || '%')
  order by a.created_at asc;
end;
$$;

