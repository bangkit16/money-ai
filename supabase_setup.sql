-- 1. TABEL PROFILES
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  is_pro boolean not null default false,
  pro_expires_at timestamptz,
  ai_daily_usage int not null default 0,
  last_ai_usage_date date not null default current_date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2. TABEL REKENING / ACCOUNT
create table if not exists public.account (
  id bigint primary key,
  account_name text not null,
  created_at timestamptz not null default now(),
  user_id uuid not null references auth.users(id) on delete cascade,
  is_primary boolean not null default false,
  exclude_from_total boolean not null default false
);

-- 3. TABEL KATEGORI TRANSAKSI
create table if not exists public.category_transaction (
  id bigint generated by default as identity primary key,
  category text not null,
  category_en text,
  slug text not null unique,
  icon text not null,
  category_type text
);

-- 4. TABEL TRANSAKSI
create table if not exists public.transaction (
  id bigint primary key,
  created_at timestamptz not null default now(),
  transaction text,
  amount numeric not null default 0,
  transaction_type text not null check (transaction_type in ('INCOME', 'EXPENSE', 'TRANSFER')),
  category_id bigint references public.category_transaction(id) on delete set null,
  account_id bigint references public.account(id) on delete set null,
  to_account_id bigint references public.account(id) on delete set null,
  transaction_date timestamptz not null default now(),
  user_id uuid not null references auth.users(id) on delete cascade
);

-- ==========================================================
-- ROW LEVEL SECURITY (RLS)
-- ==========================================================

alter table public.profiles enable row level security;
alter table public.account enable row level security;
alter table public.category_transaction enable row level security;
alter table public.transaction enable row level security;

-- Policies: Profiles
drop policy if exists "Users can view own profile" on public.profiles;
create policy "Users can view own profile"
  on public.profiles for select
  to authenticated
  using ((select auth.uid()) = id);

drop policy if exists "Users can insert own profile" on public.profiles;
create policy "Users can insert own profile"
  on public.profiles for insert
  to authenticated
  with check ((select auth.uid()) = id);

revoke update on public.profiles from authenticated;
grant update (updated_at) on public.profiles to authenticated;

drop policy if exists "Users can update non-sensitive profile columns" on public.profiles;
create policy "Users can update non-sensitive profile columns"
  on public.profiles for update
  to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

-- Policies: Account
drop policy if exists "Users can manage own accounts" on public.account;
create policy "Users can manage own accounts"
  on public.account for all
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

-- Policies: Categories
drop policy if exists "Authenticated users can read categories" on public.category_transaction;
create policy "Authenticated users can read categories"
  on public.category_transaction for select
  to authenticated
  using (true);

-- Policies: Transaction
drop policy if exists "Users can manage own transactions" on public.transaction;
create policy "Users can manage own transactions"
  on public.transaction for all
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

